import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1280,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:1420');
await page.screenshot({path:'qa/desktop.png',fullPage:true});
await page.getByLabel('电话号码',{exact:true}).fill('1002');
await page.getByRole('button',{name:'模拟拨打',exact:true}).click();
await page.getByRole('button',{name:'模拟拨打',exact:true}).count().then(n=>assert.equal(n,0));
await page.waitForTimeout(1400);
assert.equal(await page.getByText('模拟通话中',{exact:true}).count(),1);
await page.getByRole('button',{name:'静音',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'已静音',exact:true}).getAttribute('aria-pressed'),'true');
await page.getByRole('button',{name:'通话记录',exact:false}).first().click();
await page.getByRole('button',{name:'结束',exact:true}).click();
assert.equal(await page.getByText('1002',{exact:true}).count(),1);
await page.getByRole('button',{name:'联系人',exact:false}).first().click();
await page.getByLabel('搜索联系人').fill('不存在');
assert.equal(await page.getByText('没有匹配的联系人').count(),1);
await page.getByRole('button',{name:'设置',exact:false}).first().click();
await page.getByRole('button',{name:'检查运行环境'}).click();
assert.equal(await page.getByText('当前为浏览器预览。',{exact:false}).count(),1);
await page.getByRole('button',{name:'拨号',exact:false}).first().click();
await page.getByRole('button',{name:'模拟拨打',exact:true}).click();
await page.getByRole('button',{name:'结束',exact:true}).click();
await page.waitForTimeout(1400);
assert.equal(await page.getByText('模拟通话中',{exact:true}).count(),0);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'qa/mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
assert.deepEqual(errors,[]);
console.log('PASS: desktop/mobile layout, simulation, mute, navigation, hangup, cancel before connect, search, browser Rust fallback.');
await browser.close();
